# =============================================================================
# model.py —— 定义 LeNet 网络结构
#
# 【这个文件干什么】
#   定义了一个叫 LeNet 的神经网络（一个类），它负责"把一张 32x32 的彩色图片
#   变成 10 个数字"。这 10 个数字分别代表图片属于 10 个类别
#   （飞机/汽车/鸟/猫/鹿/狗/青蛙/马/船/卡车）的"得分"。
#
# 【LeNet 的整体结构（数据流向）】
#   输入图片 [N, 3, 32, 32]
#     ↓ 卷积 conv1（3→16 通道，5x5 卷积核）
#   [N, 16, 28, 28]
#     ↓ 最大池化 pool1（2x2）
#   [N, 16, 14, 14]
#     ↓ 卷积 conv2（16→32 通道，5x5 卷积核）
#   [N, 32, 10, 10]
#     ↓ 最大池化 pool2（2x2）
#   [N, 32, 5, 5]
#     ↓ 拉平 view
#   [N, 800]
#     ↓ 全连接 fc1 → fc2 → fc3
#   [N, 10]   （10 个类别的得分）
#
# 其中 N 是"一批图片的张数"（batch size），N 是多少不影响网络结构，
# 所以下面代码里写死的都是 32、5、10 这些跟单张图片有关的数字。
#
# 【小知识：import（导入）是什么意思？】
#   Python 文件之间可以互相"借用"代码。import 就是把别人写好的
#   工具/函数/类拿进来用。文件最顶部集中放 import，是 Python 的规范写法，
#   方便一眼看出这个文件依赖哪些库。
# =============================================================================

import torch.nn as nn            # nn: 神经网络(neural network)的构件库
import torch.nn.functional as F  # F: 一些"不保存参数"的函数（ReLU、softmax 等）


class LeNet(nn.Module):
    """
    定义网络类。nn.Module 是 PyTorch 所有网络的"爸爸类"（基类），
    继承它之后，PyTorch 会自动帮我们管理网络里的所有参数
    （比如卷积核、权重矩阵），训练时方便统一求梯度。

    一个类可以理解成一个"模板"，new 一个出来就是一台参数不同的机器。
    """

    # __init__ 是 Python 的"构造函数"：创建 LeNet 对象时自动调用，
    # 在这里把网络需要的每一层"搭好"（相当于搭积木）。
    def __init__(self):
        super(LeNet, self).__init__()  # 先调用父类的构造函数（Python 的要求，照抄即可）
        # ------------------------------------------------------------------
        # Conv2d 二维卷积层：
        #   nn.Conv2d(输入通道数, 输出通道数, 卷积核大小)
        #   conv1: 输入 3 通道 → 输出 16 通道，卷积核 5x5
        #
        # 【为什么要 3 通道输入？】
        #   CIFAR10 的图片是彩色照片，每个像素由 R(红) G(绿) B(蓝) 三个数组成，
        #   所以一张图片可以看成 3 张叠在一起的"灰度图"，即 3 个通道。
        #
        # 【卷积层在干什么？（数学角度）】
        #   一个 5x5 的卷积核就是一个小"窗口"，在图片上从左到右、从上到下滑动，
        #   每到一个位置，把窗口内的 5x5 个数与卷积核对应位置相乘再求和（再加一个
        #   偏置 b），得到输出上的一个数。本质上就是"二维互相关"（离散卷积的变体）。
        #   所以卷积层做的事情就是: 输出(x, y) = Σ_{i,j} 输入(x+i, y+j) * 核(i, j) + b
        #
        # 【为什么要 16 个输出通道？】
        #   每个输出通道配一套独立的卷积核（一套 5x5 的权重 + 一个偏置），
        #   相当于 16 个"不同的放大镜/特征检测器"，有的检测横边、有的检测竖边、
        #   有的检测颜色块…… 16 个通道 = 用 16 种视角观察图片。
        #
        # 【输出尺寸怎么算？】
        #   输出高 = (输入高 - 卷积核大小) / 步长 + 1
        #   conv1: (32 - 5) / 1 + 1 = 28，所以输出是 28x28
        # ------------------------------------------------------------------
        self.conv1 = nn.Conv2d(3, 16, 5)

        # MaxPool2d(窗口大小, 步长)：最大池化层
        # 在 2x2 的小窗口里取最大值，然后窗口移动 2 格（不重叠）。
        # 作用：① 尺寸减半，计算量变小；② 提取"这个区域里最明显的特征"，
        # 让网络对轻微的位移、形变不那么敏感。
        # 注意：池化不改变通道数，所以 16 进来还是 16 出去，只是 28x28 → 14x14。
        self.pool1 = nn.MaxPool2d(2, 2)

        # conv2: 16 通道 → 32 通道，5x5 卷积核
        # 输入是 pool1 的输出 [16, 14, 14]，(14 - 5) / 1 + 1 = 10 → 输出 10x10。
        # 通道数从 16 翻倍到 32：图片越来越小，但"视角"越来越多，
        # 这样信息量不会因为尺寸缩小而丢失太多。
        self.conv2 = nn.Conv2d(16, 32, 5)

        self.pool2 = nn.MaxPool2d(2, 2)

        # ------------------------------------------------------------------
        # 全连接层 nn.Linear(输入特征数, 输出特征数)：
        #   数学上就是一个矩阵乘法加偏置：y = W x + b
        #   W 的形状是 (输出特征数, 输入特征数)，x 是拉平后的图片特征向量。
        #   "全连接"的意思是：输出的每一个数，都由输入的每一个数加权求和得到，
        #   输入和输出之间完全相连（不像卷积那样只看局部窗口）。
        #
        # 为什么 fc1 的输入是 32*5*5 = 800？
        #   因为经过 conv2 + pool2 之后，特征图是 32 个通道、每张 5x5 大小，
        #   我们把它们全部拉平成一长条向量：32 × 5 × 5 = 800 个数。
        #   这一长条 800 维向量，就是网络从图片里"提炼出来"的最终特征，
        #   接下来交给全连接层做分类决策。
        # ------------------------------------------------------------------
        self.fc1 = nn.Linear(32 * 5 * 5, 120)  # 800 维特征 → 120 维
        self.fc2 = nn.Linear(120, 84)          # 120 维 → 84 维
        self.fc3 = nn.Linear(84, 10)           # 84 维 → 10 维（10 个类别，各给一个得分）

    # forward 是"前向传播"：给定输入 x，让数据按顺序流过上面搭好的各层，
    # 计算出输出。训练和预测时都走这条路径。
    def forward(self, x):
        # x 的形状：[N, 3, 32, 32]（N 张 3 通道 32x32 的图片）
        # 每行注释里都标了形状变化，方便对照：
        x = F.relu(self.conv1(x))    # input(3, 32, 32) output(16, 28, 28)
        x = self.pool1(x)            # output(16, 14, 14)
        x = F.relu(self.conv2(x))    # output(32, 10, 10)
        x = self.pool2(x)            # output(32, 5, 5)

        # view(-1, 32*5*5) 是把多维数组"拉平"成两维：
        # [N, 32, 5, 5] → [N, 800]。-1 表示"这一维自动算"，即 N = 总个数 / 800。
        # 必须拉平，因为全连接层只能吃一维向量（数学上就是矩阵乘法的要求）。
        x = x.view(-1, 32 * 5 * 5)       # output(32*5*5) = [N, 800]

        x = F.relu(self.fc1(x))      # output(120)
        x = F.relu(self.fc2(x))      # output(84)
        x = self.fc3(x)              # output(10) —— 注意！这里没有激活函数

        # 【ReLU 是什么？为什么需要它？】
        #   F.relu 就是 f(x) = max(0, x)：负数全变 0，正数不变。
        #   数学上它给网络引入"非线性"。如果去掉所有 ReLU，整个网络从头到尾
        #   只是矩阵乘法的复合，仍然是线性变换 y = W_total x + b_total，
        #   那再深的网络也顶不过一个简单的线性分类器。有了 ReLU 这样的
        #   非线性函数，网络才能逼近任意复杂的函数（万能逼近定理）。
        #
        # 【为什么最后 fc3 不接 ReLU？】
        #   fc3 输出的 10 个数叫 logits（原始得分），可能是负数也可能超过 1。
        #   我们故意不把它变成概率——因为计算损失时，CrossEntropyLoss
        #   内部自己会做 softmax（把得分变成概率分布），且数值上更稳定。
        #   具体数学形式见 train.py 里的详细注释。
        return x


