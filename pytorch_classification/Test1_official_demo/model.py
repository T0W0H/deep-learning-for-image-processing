# 【下面这段是你之前自己加的测试代码，我保留并整理规范了】
# 作用：造一批随机图片，看网络能不能跑通（顺便看看网络内部结构长什么样）。
#
# 【为什么包在 if __name__ == '__main__': 里？】
#   一个 .py 文件有两种被使用的场合：
#     ① 被直接运行（python model.py）→ 执行这里的测试代码
#     ② 被别的文件导入（train.py 里 from model import LeNet）→ 只借用类，
#        不执行测试代码（否则导入时会莫名其妙地跑一遍测试，很烦人）
#   Python 通过 __name__ 变量区分这两种场合：直接运行时它是 '__main__'。
#
# 【小知识：模块 (module)】
#   一个 .py 文件就是一个"模块"，可以被其他文件 import。
# =============================================================================
if __name__ == '__main__':
    import torch  # 这里单独 import torch（PyTorch 主库），不影响顶部风格

    # torch.rand([32, 3, 32, 32])：生成 [32, 3, 32, 32] 形状的随机数数组，
    # 数值在 0~1 之间均匀分布。相当于"造 32 张 3 通道 32x32 的随机图片"，
    # 纯粹用来测试网络结构是否搭对。
    input1 = torch.rand([32, 3, 32, 32])

    model = LeNet()  # 创建网络（新建一台"参数随机初始化"的机器）

    print(model)     # 打印网络结构：能看到每一层的名字、输入输出维度

    output = model(input1)   # 前向传播：把 32 张随机图送进网络
    print(output.shape)      # 打印输出形状，应该是 torch.Size([32, 10])：
                             # 32 张图，每张得到 10 个类别的得分 ✓
