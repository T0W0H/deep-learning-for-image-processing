# =============================================================================
# predict.py —— 用训练好的模型预测单张图片
#
# 【这个文件干什么】
#   读取训练时保存的 Lenet.pth 权重，对一张图片 1.jpg 做分类预测，
#   打印出它最可能属于的类别，比如 "cat"。
#
# 【训练 vs 预测（推断）的区别】
#   训练：有标签，算损失、求梯度、更新参数（要 backward）。
#   预测：没有标签，只需要 forward 算出结果，不需要梯度。
#   所以预测代码里到处是 torch.no_grad()，就是为了省内存、加快速度。
# =============================================================================

import torch                                 # PyTorch 主库
import torchvision.transforms as transforms  # 图片预处理工具
from PIL import Image                        # PIL：Python 的图像处理库，用来读图片

from model import LeNet                      # 导入我们自己定义的网络结构


def main():
    # ----------------------------------------------------------------------
    # 【重要！预处理必须和训练时一模一样】
    # 网络是在"标准化过的图片"上训练的（数值在 -1~1 之间）。
    # 如果预测时预处理不一样（比如不标准化），图片的数值范围就和训练时
    # 不同，网络会"不认识"它，预测结果会一塌糊涂。
    # 所以这里的三步和 train.py 里完全一致：
    #   1) Resize((32, 32))：缩放到 32x32。
    #      CIFAR10 的图片本来就是 32x32，但用户自己给的图片（比如 1.jpg）
    #      尺寸是任意的，必须先缩放到网络要求的输入尺寸。
    #   2) ToTensor()：PIL 图片 [H, W, C]、0~255 整数 → 张量 [C, H, W]、0~1 小数。
    #   3) Normalize((0.5,0.5,0.5), (0.5,0.5,0.5))：(x - 0.5) / 0.5 → -1~1。
    # ----------------------------------------------------------------------
    transform = transforms.Compose(
        [transforms.Resize((32, 32)),
         transforms.ToTensor(),
         transforms.Normalize((0.5, 0.5, 0.5), (0.5, 0.5, 0.5))])

    # 10 个类别名。网络输出的 10 个得分，下标 0~9 分别对应这里的
    # 'plane'(飞机)、'car'(汽车)、'bird'(鸟)、'cat'(猫)、'deer'(鹿)、
    # 'dog'(狗)、'frog'(青蛙)、'horse'(马)、'ship'(船)、'truck'(卡车)。
    # 下标顺序必须和训练时 CIFAR10 数据集的类别顺序一致。
    classes = ('plane', 'car', 'bird', 'cat',
               'deer', 'dog', 'frog', 'horse', 'ship', 'truck')

    net = LeNet()  # 先按 model.py 里的结构"搭"一个空网络（参数随机）

    # ----------------------------------------------------------------------
    # 把训练好的权重装进网络：
    #   torch.load('Lenet.pth')  读取保存的参数（一个字典：层名 → 参数张量）
    #   load_state_dict(...)     把字典里的参数一一填进网络里
    # 填完之后，net 就是"训练好的"那台机器了。
    # ----------------------------------------------------------------------
    net.load_state_dict(torch.load('Lenet.pth'))

    # 读取图片文件 1.jpg（注意：它必须和本文件在同一个目录下）
    im = Image.open('1.jpg')

    # 预处理三步走，得到单张图片的张量
    im = transform(im)  # [C, H, W] = [3, 32, 32]

    # ----------------------------------------------------------------------
    # 【batch 维是什么？】
    # 网络是按"一批一批"设计的：输入要求 4 维 [N, C, H, W]，
    # 第 0 维 N 是"这一批有几张图"。
    # 现在只有 1 张图 [3, 32, 32]，所以用 unsqueeze(dim=0) 在第 0 维
    # "硬塞"一个长度为 1 的维度 → [1, 3, 32, 32]（1 张图的 batch）。
    # unsqueeze 就是"增加一个大小为 1 的维度"，数学上相当于给张量
    # 外面再套一层方括号。
    # ----------------------------------------------------------------------
    im = torch.unsqueeze(im, dim=0)  # [N, C, H, W] = [1, 3, 32, 32]

    # 预测阶段不需要梯度，用 no_grad() 包起来（省内存、提速）
    with torch.no_grad():
        outputs = net(im)  # 前向传播 → [1, 10]：这张图的 10 个类别得分

        # ------------------------------------------------------------------
        # 【argmax：从得分到答案】
        # torch.max(outputs, dim=1)：在第 1 维（10 个类别的维度）上取最大值。
        # 返回一个元组 (最大值, 最大值的下标)：
        #   [0] 是 10 个得分里最大的那个数
        #   [1] 是它所在的位置（0~9），也就是"得分最高的类别的编号"
        # 得分最高 → softmax 后概率最大 → 网络最相信这个类别。
        # .numpy() 把张量转成 numpy 数组（更"轻"的 Python 数据结构）。
        # ------------------------------------------------------------------
        predict = torch.max(outputs, dim=1)[1].numpy()
        predict1 = torch.softmax(outputs, dim=1)

    # predict 是数组，长度 1（只有一张图），predict[0] 就是类别编号
    # classes[编号] 取出类别名并打印，比如 "cat"
    print(classes[int(predict)])
    print(predict1)


if __name__ == '__main__':
    main()
